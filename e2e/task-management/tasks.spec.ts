import { test, expect } from '@playwright/test'

test.beforeEach(async ({ page }) => {
  await page.addInitScript(() => {
    if (sessionStorage.getItem('e2e-initialized')) return
    localStorage.setItem('ui-ecosystem:task-management:tasks:v1', '[]')
    sessionStorage.setItem('e2e-initialized', 'true')
  })
})

test('manages tasks and updates dashboard metrics', async ({ page }) => {
  await page.goto('/tasks')
  await page.getByRole('button', { name: 'Add task' }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('Title').fill('E2E task')
  await dialog.getByLabel('Description').fill('Browser verification')
  await dialog.getByLabel('Priority').selectOption('high')
  await dialog.getByLabel('Status').selectOption('todo')
  await dialog.getByLabel('Due date').fill('2027-01-15')
  await dialog.getByRole('button', { name: 'Save' }).click()
  await expect(dialog).not.toBeVisible()
  const row = page
    .getByRole('table', { name: 'Task list' })
    .getByRole('row')
    .filter({ hasText: 'E2E task' })
  await expect(row).toContainText('high')
  await page.getByLabel('Search').fill('Browser verification')
  await expect(row).toBeVisible()
  await page.getByLabel('Priority').selectOption('low')
  await expect(row).toHaveCount(0)
  await page.getByLabel('Priority').selectOption('high')
  await row.getByRole('button', { name: 'Edit' }).click()
  await dialog.getByLabel('Status').selectOption('completed')
  await dialog.getByRole('button', { name: 'Save' }).click()
  await expect(row).toContainText('Completed')
  await page.getByLabel('Status').selectOption('todo')
  await expect(row).toHaveCount(0)
  await page.getByLabel('Status').selectOption('completed')
  await expect(row).toBeVisible()
  await page.reload()
  await expect(row).toContainText('Completed')
  await page.getByRole('button', { name: 'Dashboard', exact: true }).click()
  await expect(page.locator('.metrics .metric')).toHaveText(['1', '0', '1', '0'])
  await page.getByRole('button', { name: 'View tasks' }).click()
  await row.getByRole('button', { name: 'Delete' }).click()
  await dialog.getByRole('button', { name: 'Delete', exact: true }).click()
  await expect(page.getByText('No matching tasks.')).toBeVisible()
  await page.reload()
  await expect(page.getByText('No matching tasks.')).toBeVisible()
})
