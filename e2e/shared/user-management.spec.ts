import { test, expect } from '@playwright/test'

test('creates, filters, edits, persists and deletes a user', async ({ page }) => {
  await page.goto('/users')
  await page.getByRole('button', { name: 'Add user', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('First name').fill('E2E')
  await dialog.getByLabel('Last name').fill('Tester')
  await dialog.getByLabel('Email').fill('e2e@example.com')
  await dialog.getByLabel('Role').fill('Reviewer')
  await dialog.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  const table = page.getByRole('table', { name: 'Users' })
  const row = table.getByRole('row').filter({ hasText: 'e2e@example.com' })
  await expect(row).toContainText('E2E Tester')
  await page.getByLabel('Search').fill('e2e@example.com')
  await expect(table.getByRole('row')).toHaveCount(2)
  await row.getByRole('button', { name: 'Edit' }).click()
  await dialog.getByLabel('Role').fill('Editor')
  await dialog.getByLabel('Active user').uncheck()
  await dialog.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await expect(row).toContainText('Editor')
  await page.getByLabel('Status', { exact: true }).selectOption('active')
  await expect(row).toHaveCount(0)
  await page.getByLabel('Status', { exact: true }).selectOption('inactive')
  await expect(row).toContainText('Inactive')
  await page.reload()
  await expect(row).toContainText('Editor')
  await row.getByRole('button', { name: 'Delete' }).click()
  await dialog.getByRole('button', { name: 'Cancel' }).click()
  await expect(row).toBeVisible()
  await row.getByRole('button', { name: 'Delete' }).click()
  await dialog.getByRole('button', { name: 'Delete', exact: true }).click()
  await expect(row).toHaveCount(0)
  await page.reload()
  await expect(table).toBeVisible()
  await expect(row).toHaveCount(0)
})

test('rejects whitespace-only required user fields', async ({ page }) => {
  await page.goto('/users')
  await page.getByRole('button', { name: 'Add user', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('First name').fill('   ')
  await dialog.getByLabel('Last name').fill('Tester')
  await dialog.getByLabel('Email').fill('e2e@example.com')
  await dialog.getByLabel('Role').fill('Reviewer')
  await dialog.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(dialog.getByText('Enter all fields and a valid email address.')).toBeVisible()
  await dialog.getByRole('button', { name: 'Cancel' }).click()
  await expect(dialog).not.toBeVisible()
})
